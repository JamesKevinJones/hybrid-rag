"""Create a local `.env` from `.env.example`, safely.

    uv run python scripts/setup_env.py          # create if absent, then report
    uv run python scripts/setup_env.py --check  # report only, never write

Three safety properties, each enforced rather than assumed:

1. **It refuses to write unless `.env` is genuinely ignored by git.** Not "is
   the pattern in .gitignore" - `git check-ignore` is asked directly, because a
   later negation rule (`!.env`) or a different ignore file can un-ignore a
   pattern that is still visibly present higher up. Creating a credentials file
   that git is willing to stage is the one failure this script exists to
   prevent, so it is checked with the tool that actually decides.

2. **It never overwrites an existing `.env`.** That file may hold a real key,
   and a template that clobbers it is a script that deletes credentials.

3. **It never prints a secret.** Status output says whether a key is present
   and how long it is, never what it is - terminals get scrolled, screenshotted
   and pasted into issues.

Not having a key is a supported state, not a failure. The system runs fully
offline; every escalation degrades to a local answer with zero cloud tokens.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ENV = REPO_ROOT / ".env"
EXAMPLE = REPO_ROOT / ".env.example"

KEY_NAMES = ("ANTHROPIC_API_KEY", "HYBRID_RAG_ANTHROPIC__API_KEY")

TEMPLATE_HEADER = """# Local environment. GITIGNORED - never commit this file.
# Generated by scripts/setup_env.py from .env.example.
#
# Level 2 (Claude) is OPTIONAL. Leave the key line commented out and the system
# runs fully offline: every escalation degrades to a local answer, spends zero
# cloud tokens, and records a `frontier_unavailable` flag in the audit ledger.
#
# To enable Level 2, uncomment the line below and paste your key after the `=`.
# ANTHROPIC_API_KEY=

"""


def is_git_ignored(path: Path) -> bool | None:
    """Ask git, not the .gitignore text. None if git cannot answer."""
    try:
        # Fixed argv; `path` is interpolated as an argument, never as shell text.
        completed = subprocess.run(
            ["git", "check-ignore", "-q", str(path)],
            cwd=REPO_ROOT,
            capture_output=True,
            timeout=30,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    # 0 = ignored, 1 = not ignored, 128 = not a git repo or other failure.
    if completed.returncode == 0:
        return True
    if completed.returncode == 1:
        return False
    return None


def key_status() -> str:
    """Whether a key is configured. Never what it is."""
    if not ENV.exists():
        return "no .env file"
    for raw in ENV.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        if name.strip() in KEY_NAMES and value.strip():
            return f"{name.strip()} is set ({len(value.strip())} characters)"
    return "no key set - offline mode, which is fully supported"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="report status without writing anything"
    )
    args = parser.parse_args()

    ignored = is_git_ignored(ENV)
    if ignored is False:
        print("REFUSING TO WRITE: git does not ignore .env in this repository.", file=sys.stderr)
        print("Add `.env` to .gitignore and re-run. A credentials file that git", file=sys.stderr)
        print("is willing to stage is exactly what this script exists to prevent.", file=sys.stderr)
        return 2
    if ignored is None:
        print("WARNING: could not ask git whether .env is ignored (not a repo?).")
        print("Verify manually before putting a real key in it.")

    if ENV.exists():
        print(f".env already exists at {ENV}")
        print(f"  status: {key_status()}")
        print("  left untouched - it may hold a real key")
        return 0

    if args.check:
        print(f"no .env at {ENV}")
        print("  run without --check to create one from .env.example")
        print("  status: offline mode, which is fully supported")
        return 0

    body = EXAMPLE.read_text(encoding="utf-8") if EXAMPLE.exists() else ""
    if not body:
        print(f"WARNING: {EXAMPLE.name} is missing; writing a minimal template instead.")
    ENV.write_text(TEMPLATE_HEADER + body, encoding="utf-8")

    print(f"created {ENV}")
    print(f"  git-ignored: {'yes' if ignored else 'UNVERIFIED - check before adding a key'}")
    print(f"  status: {key_status()}")
    print()
    print("Level 2 stays off until you uncomment ANTHROPIC_API_KEY and paste a key.")
    print("Until then `hybrid-rag ask` answers locally and spends nothing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
